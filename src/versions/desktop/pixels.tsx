/** A pixel map as SVG rects, with its hard shadow. */
function rects(map: string[], shadow = true) {
  const out: { x: number; y: number; c: string }[] = [];
  const filled = (x: number, y: number) => map[y] && map[y][x] && map[y][x] !== '.';
  if (shadow) for (let y = 0; y < map.length; y++) for (let x = 0; x < map[y].length; x++) {
    if (filled(x, y) && !filled(x + 1, y + 1)) out.push({ x: x + 1, y: y + 1, c: C.k });
  }
  for (let y = 0; y < map.length; y++) for (let x = 0; x < map[y].length; x++) {
    const ch = map[y][x];
    if (ch !== '.' && C[ch]) out.push({ x, y, c: C[ch] });
  }
  return out;
}

export function Px({ name, size = 64, shadow = true, className }: { name: keyof typeof MAPS; size?: number; shadow?: boolean; className?: string }) {
  const r = rects(MAPS[name], shadow);
  return (
    <svg className={className} viewBox="0 0 17 17" width={size} height={size} shapeRendering="crispEdges" aria-hidden="true" focusable="false">
      {r.map((p, i) => <rect key={i} x={p.x} y={p.y} width="1" height="1" fill={p.c} />)}
    </svg>
  );
}

