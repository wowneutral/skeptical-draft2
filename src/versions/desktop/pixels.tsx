const svgOf = (map: string[], px: number) => {
  const w = Math.max(...map.map((r) => r.length)), h = map.length;
  let s = '';
  for (let y = 0; y < h; y++) for (let x = 0; x < map[y].length; x++) {
    const ch = map[y][x];
    if (ch === '#') s += `<rect x='${x}' y='${y}' width='1' height='1' fill='%2315171d'/>`;
    else if (ch === 'o') s += `<rect x='${x}' y='${y}' width='1' height='1' fill='%23f3f1ea'/>`;
  }
  return `url("data:image/svg+xml,<svg xmlns='http://www.w3.org/2000/svg' width='${w * px}' height='${h * px}' viewBox='0 0 ${w} ${h}' shape-rendering='crispEdges'>${s}</svg>")`;
};
